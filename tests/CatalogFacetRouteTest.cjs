const assert = require('node:assert/strict');
const {buildRoute} = require('../public/js/catalog-facets.js');
const base = 'https://its-center.ru/category/industrialnye-shiny';
const size = {id:'235',group:'1',alias:'6.50-10'};
const size2 = {id:'236',group:'1',alias:'7.00-12'};
const ekka = {id:'83',group:'2',alias:'ekka'};
const heng = {id:'121',group:'2',alias:'hengruida'};
const u = (selected, primary='', fields={}) => new URL(buildRoute(base,selected,primary,fields));
assert.equal(u([size]).pathname,'/category/industrialnye-shiny/6.50-10');
assert.equal(u([ekka,size],'235').pathname,'/category/industrialnye-shiny/6.50-10','Existing main survives DOM order');
assert.equal(u([size,ekka]).searchParams.get('filter'),'83','Different facet is an additional parameter');
assert.equal(u([size,ekka,heng]).pathname,'/category/industrialnye-shiny/6.50-10','OR in extra brand group preserves size landing');
assert.equal(u([size,size2],'235').pathname,'/category/industrialnye-shiny','Two sizes must not pretend to be one size landing');
assert.equal(u([size,size2],'235').searchParams.get('filter'),'235,236');
assert.equal(u([size,size2,ekka],'235').pathname,'/category/industrialnye-shiny/ekka','Unambiguous remaining group becomes landing');
assert.equal(u([]).href,base,'Empty clears route');
assert.equal(u([size],'',{sort:'stock',status:'',perpage:'24'}).search,'','Default controls keep the clean landing URL');
assert.equal(u([size], '',{sort:'price_asc',in_stock:'1',page:'99',bad:'x'}).search,'?sort=price_asc&in_stock=1','Whitelist, reset pagination');
assert.equal(u([{id:'1',group:'1',alias:'12.5/80-18'}]).pathname,'/category/industrialnye-shiny/12.5/80-18','Slash size route stays compatible');
console.log('Facet routing: first choice, preserved landing, OR-safe fallback, extra groups, whitelist and pagination OK');
